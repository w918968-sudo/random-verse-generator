// Generates dist/sw.js with a precache manifest of every file in dist/.
// Runs after `astro build` (hooked into the `build` npm script). No deps.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, sep } from 'node:path';
import { createHash } from 'node:crypto';

const __dirname = dirname(fileURLToPath(import.meta.url));
const dist = join(__dirname, '..', 'dist');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

// Large data payloads (full Bible, future semantic indexes/models) are loaded
// lazily at runtime and are network-first via the /data/ handler — precaching
// them would balloon the install. Skip anything above this size.
const MAX_PRECACHE_BYTES = 1_000_000;

const files = walk(dist)
  .filter((p) => !p.endsWith(`${sep}sw.js`))
  .filter((p) => statSync(p).size <= MAX_PRECACHE_BYTES)
  .map((p) => {
    let url = '/' + relative(dist, p).split(sep).join('/');
    // Cloudflare redirects /foo/index.html -> /foo/; precache the canonical URL.
    if (url.endsWith('/index.html')) url = url.slice(0, -'index.html'.length);
    return url;
  })
  .sort();

const version = createHash('sha1').update(files.join('\n')).digest('hex').slice(0, 8);
const precache = JSON.stringify(files, null, 2);

const sw = `// Generated by scripts/build-sw.mjs — do not edit by hand.
const CACHE = 'versewell-${version}';
const PRECACHE = ${precache};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

async function cachedNavigation(req) {
  const direct = await caches.match(req);
  if (direct) return direct;
  return caches.match('/');
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;

  // App pages: network-first so updates ship immediately; cached copy offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(req, copy));
          return res;
        })
        .catch(() => cachedNavigation(req))
    );
    return;
  }

  // Verse data: network-first (always fresh online), cache fallback offline.
  if (url.pathname.startsWith('/data/')) {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        })
        .catch(() => caches.match(req))
    );
    return;
  }

  // Static assets are content-hashed: cache-first, fall back to network.
  event.respondWith(caches.match(req).then((cached) => cached || fetch(req)));
});
`;

writeFileSync(join(dist, 'sw.js'), sw);
console.log(`Wrote dist/sw.js (${files.length} precached, cache versewell-${version})`);
